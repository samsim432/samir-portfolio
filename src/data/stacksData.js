const createRoadmap = ({
  foundations = [],
  core = [],
  frameworks = [],
  data = [],
  quality = [],
  production = [],
  advanced = [],
  tools = [],
}) => {
  const stages = [
    {
      title: "Foundations",
      description:
        "Build the fundamental knowledge required before moving into specialized tools and frameworks.",
      topics: foundations,
      tools: tools.slice(0, 3),
    },
    {
      title: "Core Skills",
      description:
        "Develop the core technical skills used every day in this career path.",
      topics: core,
      tools: tools.slice(0, 4),
    },
    {
      title: "Frameworks & Ecosystem",
      description:
        "Learn the frameworks, libraries, platforms, and workflows commonly used in professional projects.",
      topics: frameworks,
      tools: tools.slice(1, 5),
    },
    {
      title: "Data & Integration",
      description:
        "Learn how applications communicate, persist information, and integrate with external systems.",
      topics: data,
      tools: tools.slice(2, 6),
    },
    {
      title: "Testing & Quality",
      description:
        "Learn professional approaches for reliability, testing, maintainability, security, and code quality.",
      topics: quality,
      tools: tools.slice(-4),
    },
    {
      title: "Production & Deployment",
      description:
        "Take projects from development into production using deployment, monitoring, automation, and operational practices.",
      topics: production,
      tools: tools.slice(-5),
    },
    {
      title: "Advanced Practice",
      description:
        "Go beyond tutorials by studying advanced concepts, architecture, performance, and real-world engineering decisions.",
      topics: advanced,
      tools: tools,
    },
  ];

  return stages
    .filter((stage) => stage.topics.length > 0)
    .map((stage, index) => ({
      step: index + 1,
      ...stage,
    }));
};


